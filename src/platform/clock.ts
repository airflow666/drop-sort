/**
 * Часы игры.
 *
 * Всё, что решается календарём или отсчётом, — награда за вход, недельный
 * пропуск, вызов дня, смена сезона, восстановление попыток блица и сам таймер
 * забега — берёт время отсюда, а не из `Date.now()`.
 *
 * Причина ровно одна и названа в документации площадки («Серверное время»):
 * часы устройства игрок волен перевести. На них ежедневная награда выдаётся
 * сколько угодно раз за вечер, недельный пропуск растягивается на месяц,
 * вызов дня переигрывается до лучшего результата, а таймер блица —
 * единственная валюта тамошнего лидерборда — останавливается переводом
 * стрелок назад. `ysdk.serverTime()` одинаков на всех устройствах и к такому
 * устойчив.
 *
 * Источник ставится один раз при старте (`installClock` в initPlatform) через
 * модульную переменную, а не протаскивается параметром: время читают полтора
 * десятка мест в мете, и менять их сигнатуры ради одного вызова в точке входа
 * дороже, чем держать одну точку установки. Без установки — часы устройства:
 * так работают локальная разработка и тесты в Node.
 */

let source: (() => number) | null = null;

/** Подключить часы площадки. Вызывается один раз, из initPlatform. */
export function installClock(fn: () => number): void {
  source = fn;
}

/** Только для тестов: вернуть часы устройства. */
export function resetClock(): void {
  source = null;
}

/**
 * Текущее время в миллисекундах.
 *
 * Отказ источника не должен ронять игру: невалидное значение или исключение
 * молча уводят на часы устройства — накрутка хуже, чем неработающая игра,
 * но ненамного, а неработающая игра — это ещё и провал модерации.
 */
export function now(): number {
  if (source) {
    try {
      const t = source();
      if (typeof t === 'number' && Number.isFinite(t) && t > 0) return t;
    } catch {
      /* площадка не ответила — считаем по устройству */
    }
  }
  return Date.now();
}

/**
 * Календарный день, `YYYY-MM-DD`, по UTC.
 *
 * Именно по UTC, а не по местному времени игрока: серверное время защищает от
 * перевода ЧАСОВ, но часовой пояс остаётся настройкой устройства, и на местной
 * дате сутки по-прежнему сдвигались бы одним переключением пояса. Ровно так же
 * считается номер дня для вызова дня (`levels/provider.ts`), и раньше эти два
 * счётчика расходились: вызов дня менялся в полночь UTC, а отметка «пройден» —
 * в местную полночь, и в Москве между 00:00 и 03:00 один и тот же уровень
 * можно было сдать в лидерборд второй раз.
 */
export function dayKey(ts = now()): string {
  return new Date(ts).toISOString().slice(0, 10);
}

/** День `YYYY-MM-DD` плюс N суток (N может быть отрицательным). */
export function addDays(key: string, days: number): string {
  const base = Date.parse(`${key}T00:00:00Z`);
  if (Number.isNaN(base)) return key;
  return dayKey(base + days * 86_400_000);
}

/**
 * Сколько суток от дня `a` до дня `b`. Для нечитаемых дат — заведомо большое
 * число: неизвестная дата должна выглядеть как «очень давно», а не как
 * «сегодня», иначе повреждённое сохранение начнёт печатать награды.
 */
export function daysBetween(a: string, b: string): number {
  const pa = Date.parse(`${a}T00:00:00Z`);
  const pb = Date.parse(`${b}T00:00:00Z`);
  if (Number.isNaN(pa) || Number.isNaN(pb)) return 99;
  return Math.round((pb - pa) / 86_400_000);
}
